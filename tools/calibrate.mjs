#!/usr/bin/env node
// calibrate.mjs - Build data/botstyle_calibration.json
//
// Scores card-sized chunks (first CHUNK words of each creative-writing output in
// results/*.json) and records percentiles of each metric. botstyle.js maps a rate
// to 0..1 as rate / p90, i.e. "1.0 = as sloppy as the sloppiest 10% of AI chunks".
//
// Usage: node tools/calibrate.mjs [--chunk 700]

import { readFileSync, writeFileSync, readdirSync } from 'fs';
import { createRequire } from 'module';
import { loadBotstyle, scoreWeighted } from '../js/botstyle.js';
import { scoreText as scoreContrast } from '../js/contrast-detector.js';
import { scoreStructures } from '../js/ai-structures.js';
import { setPosTagger } from '../js/pos-tagger.js';

const require = createRequire(import.meta.url);
const root = new URL('../', import.meta.url);
const args = process.argv.slice(2);
const CHUNK = Number(args[args.indexOf('--chunk') + 1]) || 700;

global.fetch = async (url) => {
  const content = readFileSync(new URL(url.replace(/^\.\//, ''), root), 'utf-8');
  return { ok: true, json: async () => JSON.parse(content) };
};
const quiet = () => { const o = { ...console }; for (const k of ['log', 'group', 'groupEnd', 'warn', 'error']) console[k] = () => {}; return () => Object.assign(console, o); };
const pct = (a, p) => { const s = [...a].sort((x, y) => x - y); return s[Math.min(s.length - 1, Math.floor(p * s.length))]; };

function firstWords(text, n) {
  const rx = /[A-Za-z]+(?:'[A-Za-z]+)?/g; let m, k = 0, end = text.length;
  while ((m = rx.exec(text))) { if (++k === n) { end = m.index + m[0].length; break; } }
  return text.slice(0, end);
}

async function main() {
  await loadBotstyle('./data/');
  setPosTagger(require('wink-pos-tagger')());
  const vals = { words: [], phrases: [], structures: [], emdash: [] };
  const perModel = {};
  for (const f of readdirSync(new URL('results/', root)).filter(f => f.endsWith('.json'))) {
    const v = Object.values(JSON.parse(readFileSync(new URL('results/' + f, root), 'utf-8')))[0];
    const mv = perModel[f.replace(/\.json$/, '')] = { words: [], phrases: [], structures: [], emdash: [] };
    for (const s of v.samples || []) {
      if (s.prompt_index >= 150 || !s.output) continue;   // creative prompts only
      const t = firstWords(s.output, CHUNK);
      const w = scoreWeighted(t);
      if (w.nWords < CHUNK * 0.5) continue;
      const restore = quiet(); const c = scoreContrast(t); restore();
      const sx = scoreStructures(t, c.matches || []);
      for (const [k, x] of [['words', w.words.rate], ['phrases', w.phrases.rate], ['structures', sx.rate], ['emdash', sx.emdash.rate]]) { vals[k].push(x); mv[k].push(x); }
    }
  }
  const summ = a => ({ n: a.length, p10: pct(a, .1), p25: pct(a, .25), p50: pct(a, .5), p75: pct(a, .75), p90: pct(a, .9), p99: pct(a, .99) });
  const out = {
    _about: `Percentiles of botstyle metric rates over ${vals.words.length} AI creative-writing chunks of ~${CHUNK} words (results/*.json, ${Object.keys(perModel).length} models). Generated by tools/calibrate.mjs.`,
    chunk_words: CHUNK,
    words: summ(vals.words), phrases: summ(vals.phrases), structures: summ(vals.structures), emdash: summ(vals.emdash),
    per_model_median: Object.fromEntries(Object.entries(perModel).map(([m, x]) => [m, { words: pct(x.words, .5), phrases: pct(x.phrases, .5), structures: pct(x.structures, .5), emdash: pct(x.emdash, .5) }])),
  };
  writeFileSync(new URL('data/botstyle_calibration.json', root), JSON.stringify(out, null, 2));
  for (const k of ['words', 'phrases', 'structures', 'emdash']) console.log(k.padEnd(9), JSON.stringify(out[k], (key, x) => typeof x === 'number' ? +x.toFixed(3) : x));
}
main();
